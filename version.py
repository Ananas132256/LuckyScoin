def get_latest():
    """Последний релиз."""
    return CHANGELOG[0] if CHANGELOG else None


def get_full_changelog(limit=5):
    """Последние N релизов."""
    return CHANGELOG[:limit]


def format_changelog(limit=5) -> str:
    """Красивый текст для отправки в Telegram."""
    lines = [
        f"🎰 <b>LuckyScoin</b> • версия <b>{VERSION}</b>",
        f"📅 <i>{RELEASE_DATE}</i>",
        "",
        "━━━━━━━━━━━━━━━━━━",
        "",
    ]
    for release in get_full_changelog(limit):
        lines.append(f"<b>📌 v{release['version']}</b>  <i>({release['date']})</i>")
        for change in release["changes"]:
            lines.append(f"  {change}")
        lines.append("")

    lines.append("━━━━━━━━━━━━━━━━━━")
    lines.append("🪳 <b>Бот:</b> @LuckyScoin_bot")
    return "\n".join(lines)